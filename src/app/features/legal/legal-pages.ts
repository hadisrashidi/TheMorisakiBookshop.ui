// (API BACKLOG task 26): every number below (days, amounts) must be checked and
// changed to the real policy before the shop opens. The same numbers are in the FAQ page.
function createPage(title: string, description: string, sections: string[][]): LegalPageModel {
  const page = new LegalPageModel();
  page.title = title;
  page.description = description;

  for (const pair of sections) {
    page.sections.push({ heading: pair[0], text: pair[1] });
  }

  return page;
}

